	 public Stack<SrcRefTrgtMM> getAllAssocCollection_MM()
	 {	
	  	for(EClass node: nodes){
	  		var nodeAssocCollection = getAllNodeAssocCollection_MM(node);
	  		if(nodeAssocCollection.size()>0){
	  			allPathEdges.addAll(nodeAssocCollection);
	  		}	  		
	  	}
	  	
	  	return allPathEdges;
	 }
	  
	 public HashSet<SrcRefTrgtMM> getAllNodeAssocCollection_MM(EClass src)
	 {
	  	var allNodeAssociations = new HashSet<SrcRefTrgtMM>();		  	
		var features = new ArrayList<EStructuralFeature>(src.getEStructuralFeatures());
		for (EStructuralFeature r : features) {
			if(r instanceof  EReference){			
				  try{
					ArrayList<EClass>  AllTargets= EMFUtils.getAllTargetsMM(src,(EReference) r);
		  			
			  		if(AllTargets != null && AllTargets.size()>0){
				  		for (EClass target:AllTargets){
				  			SrcRefTrgtMM newERef= new SrcRefTrgtMM(src,(EReference) r,target);
				  			allNodeAssociations.add(newERef);
				  			var subClasses = EMFUtils.getAllSubClassesMM(target);
				  			for (EClass sc:subClasses){				  				
				  				SrcRefTrgtMM newERef2= new SrcRefTrgtMM(src,(EReference) r,sc);
				  				allNodeAssociations.add(newERef2);
				  			}				  			
				  		}
			  		}
		  		}catch(Exception ex){	  			
		  		}	  		
	  		}
	  	}
	  	return allNodeAssociations;
	 }	 
