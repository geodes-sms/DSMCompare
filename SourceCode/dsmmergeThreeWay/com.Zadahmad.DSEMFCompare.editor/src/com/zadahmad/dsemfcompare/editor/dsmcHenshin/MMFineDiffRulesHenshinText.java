	public ArrayList<SrcRefTrgtMM> getUniqueSrcRefTrgt() {
		var currentNode = root;
	    var visitedSrcRefTrgtMMs = new HashSet<SrcRefTrgtMM>();
	    var visitedNodes = new HashSet<EClass>();	    
	    ArrayList<SrcRefTrgtMM> processedSrcRefTrgtMMs= new ArrayList<SrcRefTrgtMM>();
	    processedSrcRefTrgtMMs.add(new SrcRefTrgtMM(root,null,null));
	    
	    SrcRefTrgtMM top = null;
	    //out.println("ERef: "+node.getName());
	   do{
		    nodes.add(currentNode);	
			visitedNodes.add(currentNode);	
			var srcRefTrgtMMs = getAllNodeAssocCollection_MM(currentNode);
		    if(srcRefTrgtMMs.size()>0){				    	
			    for(SrcRefTrgtMM r:srcRefTrgtMMs){		    				    	
			    	if(!isVisited(r,visitedSrcRefTrgtMMs)){
			    		inStockSrcRefTrgtMMs.push(r);					    		
			    		visitedSrcRefTrgtMMs.add(r);	  				    		
			    	}					    	
			    }
		    }					    
		    do{	
		    	try {
		    	top = inStockSrcRefTrgtMMs.peek();	
			    processedSrcRefTrgtMMs.add(top);
		    	//3. out.print(eReference ADD DELETE))
		    	//out.println("ERef Poped: "+top.source.getName() + "-"+top.eReference.getName()+ "->"+top.target.getName());
			    inStockSrcRefTrgtMMs.pop();
			    currentNode=null;
			    if(top!=null)
				    currentNode = top.target;	
		    	}catch(EmptyStackException ex) {
		    		currentNode=null;
		    		break;
		    	}
		    }while (visitedNodes.contains(currentNode) && inStockSrcRefTrgtMMs.size()>0);// || (node==null && stackRefTypes.size()>0) );							    	    
	   }while(currentNode!=null);//inStockSrcRefTrgtMMs.size()>0);
	   return processedSrcRefTrgtMMs;
	}
	  
	public boolean isVisited(SrcRefTrgtMM r,HashSet<SrcRefTrgtMM> visitedRefs){
    	var vRs=visitedRefs.toArray();
    	for(int i=0;i<vRs.length;i++){
    		SrcRefTrgtMM v=(SrcRefTrgtMM) vRs[i];
    		i++;
    		if(v.source.equals(r.source) && v.target.equals(r.target) && v.eReference.equals(r.eReference)){
				return true;
    		}					    			
    	}
    	return false;
  }
	 
