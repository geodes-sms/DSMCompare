	 public String defineNode(EObject n, String actionText, String henshinFileType)
	 {
	 	var nodeDef="\t\t\t\t "+actionText;
	 	if(actionText == "preserve" || actionText == "forbid")
	 		nodeDef+= "\t\t\t";
	 	else
	 		nodeDef+= "\t\t\t\t";
	 	
	 	nodeDef += createNode(n)+":"+EMFUtils.getSuperClassName(n);
	 	
	 	var diffKindVal = "";
	 	var diffKindLeftDef= "";
	 	var diffKindRightDef= "";
	 	if(henshinFileType=="DSDiff"){
	 		diffKindVal = getStringAttrDef(n,"diff_kind");
	 		if(!diffKindVal.contains("NON")){
	 			diffKindLeftDef  = diffKindVal.replace("diff_kind","diff_kind_Left");	 
	 			diffKindRightDef  = diffKindVal.replace("diff_kind","diff_kind_Right");	
	 		}		
	 	}
	 		 	
	 	if(diffKindLeftDef != "" || diffKindRightDef !="" )
	 		{
	 		nodeDef += "{";	 		
	 		
	 		if(diffKindLeftDef!=""){
	 			nodeDef += "\n\t\t\t\t\t" + actionText + " " + diffKindLeftDef;
	 		}
	 		if(diffKindRightDef!=""){
	 			nodeDef += "\n\t\t\t\t\t" + actionText + " " + diffKindRightDef;
	 		}	 		
		 	nodeDef +="\n" + "\t\t\t\t}";	 	
	 	}
	 	
	 	return nodeDef;
	 } 
	 
	 public String getStringAttrDef(EObject n, String attrName)
	 {
	 	var attr= EMFUtils.getEAttributeByName(n,attrName);
	 	if(attr==null){
	 		return "";
	 	}	 		
	 	else{
	 		if(attr.getEAttributeType().eClass().getName().toLowerCase()=="eenum"){	
	 			var id_PatternLhs=EMFUtils.getAttrValueByAttrName(n,"ID_Pattern").toString();			
				return  attrName +" = " + "n" + id_PatternLhs + attrName;	 		}
	 		else{
	 			return attrName + " = " + "\"\\\"" + n.eGet(attr).toString()+ "\\\"\"";
	 		}
	 	}
	 }
	 
	 public void defineEdges(){
	  	edges= new ArrayList<String>();
	  	for(SrcRefTrgtMM ERefC: getAllAssocCollection_MM()){
	  		if(nodes.contains(ERefC.source) && nodes.contains(ERefC.target))
	  		{ 		 
		  		if((EMFUtils.getAttrValueByAttrName(ERefC.source,"ID_Pattern").toString().contains("-") == true)
		  			||  (EMFUtils.getAttrValueByAttrName(ERefC.target,"ID_Pattern").toString().contains("-") == true))
		  		{
		  			var AssocDef= 	
		  						"("+
		  						"create\t\t" + 
		  						createNodeNumber(ERefC.source)+
		  						"->" + 
		  						createNodeNumber(ERefC.target)+
		  						":"+
		  						ERefC.eReference.getName()+
		  						"),";
					edges.add(AssocDef);
		  		}
		  		else if(!ERefC.source.eClass().getName().toLowerCase().contains("domainspecificdiff"))
		  		{
		  			var AssocDef= 	
		  						"("+
		  						"preserve\t" + 
		  						createNodeNumber(ERefC.source)+
		  						"->" + 
		  						createNodeNumber(ERefC.target)+
		  						":"+
		  						ERefC.eReference.getName()+
		  						"),";
					edges.add(AssocDef);
		  		}
	  		}   		
		}
		if(edges.size()>0)	 
		{
	  		var s =edges.get(edges.size()-1);
	  		s= s.substring(0, s.length() - 1);
	  		edges.set(edges.size()-1,s);
		}
	  }

	 public Boolean addParamToRuleSignature(String param){
	  	if(param!=null && param!="" && !ruleSignature.contains(param)){
			if(ruleSignature!="" && ruleSignature!=null)
			 	{ ruleSignature += "," + param; }
			else 
			 	{ ruleSignature += param; }	
			return true;	
		}
		return false;	 	
	 }
	  
